/* ---------- Derived helpers ---------- */

/** All unique genres across the catalogue */
export const allGenres: string[] = [
  ...new Set(animeList.flatMap((a) => a.genres.split("|"))),
].sort();

/** All unique studios across the catalogue */
export const allStudios: string[] = [
  ...new Set(animeList.flatMap((a) => a.studios.split("|"))),
].sort();

/** All unique years (as strings for filter chips) */
export const allYears: string[] = [
  ...new Set(
    animeList
      .map((a) => a.year)
      .filter((y): y is number => y !== null)
      .map(String)
  ),
].sort((a, b) => Number(b) - Number(a));

/** Get display title (prefer English, fall back to romaji) */
export function displayTitle(anime: Anime): string {
  return anime.title_english || anime.title;
}
